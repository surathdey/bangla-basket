"""
menu_ai.py — AI enrichment for bulk-upload of master-menu items.

Given a `name` (and optional price hint) this module generates:
  - short_description
  - full_description
  - category            (one of the fixed set)
  - cuisine             (one of the fixed set)
  - veg_type
  - spice_level
  - allergens           (subset)
  - image_url           (data-URI PNG generated by Gemini Nano Banana)

Both the text and the image are generated via the Emergent Universal LLM Key.
"""
from __future__ import annotations

import base64
import json
import logging
import os
import re
import uuid
from pathlib import Path
from typing import Dict, List, Optional, Tuple

from dotenv import load_dotenv
try:
    from emergentintegrations.llm.chat import LlmChat, UserMessage
except ModuleNotFoundError as exc:
    if exc.name != "emergentintegrations":
        raise
    LlmChat = None
    UserMessage = None

load_dotenv()

log = logging.getLogger("curryco.menu_ai")

try:
    from brand import BRAND_NAME as _BRAND_NAME
except Exception:
    _BRAND_NAME = "Mustard Garden"

_EMERGENT_LLM_KEY = os.getenv("EMERGENT_LLM_KEY")
_TEXT_MODEL_PROVIDER = "openai"
_TEXT_MODEL_NAME = "gpt-5.4-mini"
_IMAGE_MODEL_PROVIDER = "gemini"
_IMAGE_MODEL_NAME = "gemini-3.1-flash-image-preview"  # Nano Banana

UPLOAD_DIR = Path("/app/backend/uploads/menu")
UPLOAD_DIR.mkdir(parents=True, exist_ok=True)

# The canonical field-value sets we allow the model to choose from.
CATEGORIES = ["starter", "main-veg", "main-non-veg", "rice", "curry", "dessert", "beverage", "side", "bread"]
CUISINES   = ["bengali", "north-indian", "south-indian", "indo-chinese", "fusion"]
VEG_TYPES  = ["vegetarian", "non-vegetarian", "eggitarian"]
SPICE_LVLS = ["mild", "medium", "hot"]
ALLERGENS  = ["dairy", "nuts", "seafood", "gluten"]


_TEXT_SYSTEM = (
    "You are a food-menu copywriter for an authentic Bengali & Indian cloud kitchen "
    f"based in the Greater Toronto Area called '{_BRAND_NAME}'. Given a dish name (and "
    "optional CAD price), produce a mouth-watering description AND classify the item. "
    "You MUST respond with ONLY a valid JSON object — no code fences, no prose. Schema:\n"
    "{\n"
    '  "short_description": "1 line, 8-15 words, appetizing tagline",\n'
    '  "full_description":  "2-3 sentences, ~30-60 words, describe ingredients, texture, story",\n'
    f'  "category":     "one of {CATEGORIES}",\n'
    f'  "cuisine":      "one of {CUISINES}",\n'
    f'  "veg_type":     "one of {VEG_TYPES}",\n'
    f'  "spice_level":  "one of {SPICE_LVLS}",\n'
    f'  "allergens":    "subset of {ALLERGENS} — return empty array [] if none apply"\n'
    "}\n"
    "Be accurate — biryani is 'rice', jalebi is 'dessert', paneer dishes are 'vegetarian', etc."
)


def _extract_json(txt: str) -> Optional[dict]:
    """Best-effort JSON extraction from LLM output (strips code fences etc.)."""
    if not txt:
        return None
    # remove ```json fences if present
    m = re.search(r"\{[\s\S]*\}", txt)
    if not m:
        return None
    try:
        return json.loads(m.group(0))
    except Exception:
        return None


def _fallback_text(name: str) -> dict:
    """Safe defaults if the model call fails so bulk-upload never dies."""
    return {
        "short_description": f"House-style {name} made fresh daily.",
        "full_description":  f"{name} — a {_BRAND_NAME} favourite, slow-cooked with authentic spices and served hot.",
        "category":     "curry",
        "cuisine":      "bengali",
        "veg_type":     "vegetarian",
        "spice_level":  "medium",
        "allergens":    [],
    }


def _clamp(value: str, allowed: List[str], default: str) -> str:
    v = (value or "").strip().lower()
    return v if v in allowed else default


def _sanitize(fields: dict, name: str) -> dict:
    fb = _fallback_text(name)
    return {
        "short_description": str(fields.get("short_description") or fb["short_description"])[:180],
        "full_description":  str(fields.get("full_description")  or fb["full_description"])[:600],
        "category":    _clamp(fields.get("category", ""),    CATEGORIES, fb["category"]),
        "cuisine":     _clamp(fields.get("cuisine",  ""),    CUISINES,   fb["cuisine"]),
        "veg_type":    _clamp(fields.get("veg_type", ""),    VEG_TYPES,  fb["veg_type"]),
        "spice_level": _clamp(fields.get("spice_level", ""), SPICE_LVLS, fb["spice_level"]),
        "allergens":   [a for a in (fields.get("allergens") or []) if a in ALLERGENS],
    }


async def enrich_text(name: str, price_cents: int = 0) -> dict:
    """Call GPT-5.4-mini and return the structured fields."""
    if not _EMERGENT_LLM_KEY:
        log.warning("EMERGENT_LLM_KEY not set — using fallback text")
        return _fallback_text(name)
    if LlmChat is None or UserMessage is None:
        log.warning("emergentintegrations is not installed — using fallback text")
        return _fallback_text(name)

    price_hint = f" (approx CA${price_cents/100:.2f})" if price_cents else ""
    prompt = f'Dish name: "{name}"{price_hint}. Return the JSON.'

    try:
        chat = LlmChat(
            api_key=_EMERGENT_LLM_KEY,
            session_id=f"menu-enrich-{uuid.uuid4().hex[:8]}",
            system_message=_TEXT_SYSTEM,
        ).with_model(_TEXT_MODEL_PROVIDER, _TEXT_MODEL_NAME)

        resp = await chat.send_message(UserMessage(text=prompt))
        text_out = resp if isinstance(resp, str) else str(resp)
        parsed = _extract_json(text_out)
        if not parsed:
            log.warning(f"text-enrich: could not parse JSON for {name!r}: {text_out[:200]}")
            return _fallback_text(name)
        return _sanitize(parsed, name)
    except Exception as e:
        log.warning(f"text-enrich failed for {name!r}: {e}")
        return _fallback_text(name)


async def enrich_image(name: str, description: str = "", cuisine: str = "bengali") -> str:
    """Generate a photorealistic food image, save under /uploads/menu/, return public URL path."""
    if not _EMERGENT_LLM_KEY:
        return ""
    if LlmChat is None or UserMessage is None:
        log.warning("emergentintegrations is not installed — skipping menu image generation")
        return ""

    prompt = (
        f"Photorealistic top-down food photography of '{name}', {cuisine} cuisine. "
        f"{description} "
        "Shot on a rustic wooden table with soft natural lighting, garnished traditionally, "
        "shallow depth of field, appetizing, restaurant-quality plating, no text, no watermark, "
        "square 1:1 composition."
    )

    try:
        chat = LlmChat(
            api_key=_EMERGENT_LLM_KEY,
            session_id=f"menu-img-{uuid.uuid4().hex[:8]}",
            system_message="You generate high-quality food photography for a menu.",
        ).with_model(_IMAGE_MODEL_PROVIDER, _IMAGE_MODEL_NAME).with_params(modalities=["image", "text"])

        _text, images = await chat.send_message_multimodal_response(UserMessage(text=prompt))
        if not images:
            log.warning(f"image-enrich: no images returned for {name!r}")
            return ""

        img0 = images[0]
        raw = base64.b64decode(img0["data"])
        fname = f"{uuid.uuid4().hex}.png"
        fpath = UPLOAD_DIR / fname
        fpath.write_bytes(raw)
        return f"/api/uploads/menu/{fname}"
    except Exception as e:
        log.warning(f"image-enrich failed for {name!r}: {e}")
        return ""


async def enrich_item(name: str, price_cents: int = 0, want_image: bool = True) -> dict:
    """Full enrichment: text + image. Returns dict with all AI fields."""
    text_fields = await enrich_text(name, price_cents)
    image_url = ""
    if want_image:
        image_url = await enrich_image(name, text_fields.get("short_description", ""), text_fields.get("cuisine", "bengali"))
    return {**text_fields, "image_url": image_url}
